"""
backend/app/models/telemetry.py
TelemetryEvent and Metric models.

IMPORTANT: These tables store ONLY allow-listed metadata fields.
Raw logs, passwords, tokens, and sensitive payloads are NEVER stored here.
They remain in the collector's local SQLite database only.
"""
import uuid
from datetime import datetime, timezone
from sqlalchemy import Column, String, Float, DateTime, ForeignKey, Index
from ..database import Base


class TelemetryEvent(Base):
    """
    One normalized event received from a collector.
    event_id is a UUID generated by the collector — unique per event.
    The UNIQUE constraint on event_id enforces idempotent delivery.
    If the collector retries after a network failure, the duplicate
    event_id is rejected with HTTP 409 instead of being stored twice.
    """
    __tablename__ = "telemetry_events"

    id = Column(String, primary_key=True, default=lambda: str(uuid.uuid4()))
    tenant_id = Column(String, ForeignKey("tenants.id"), nullable=False, index=True)
    source_id = Column(String, nullable=False, index=True)
    # event_id from the collector — UNIQUE enforces no-duplicate delivery
    event_id = Column(String, unique=True, nullable=False, index=True)
    utc_timestamp = Column(String, nullable=False)   # ISO-8601 UTC, transmission time
    event_time = Column(String, nullable=False)       # ISO-8601 UTC, original event time
    source_timezone = Column(String, default="UTC")
    metric_category = Column(String, nullable=False)  # cpu|memory|disk|network|security
    metric_value = Column(Float, nullable=False)
    severity = Column(String, default="info")          # info|warning|critical|resolved
    health_status = Column(String, default="excellent")
    alert_context = Column(String, default="")         # max 200 chars, pre-screened
    data_source = Column(String, default="live")
    collector_id = Column(String, nullable=True)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc))

    __table_args__ = (
        Index("ix_te_tenant_source_time", "tenant_id", "source_id", "event_time"),
    )


class Metric(Base):
    """Aggregated metric value — one row per (source, category, time) sample."""
    __tablename__ = "metrics"

    id = Column(String, primary_key=True, default=lambda: str(uuid.uuid4()))
    tenant_id = Column(String, ForeignKey("tenants.id"), nullable=False, index=True)
    source_id = Column(String, nullable=False, index=True)
    category = Column(String, nullable=False)
    value = Column(Float, nullable=False)
    utc_timestamp = Column(String, nullable=False)
    event_time = Column(String, nullable=False)
    # data_source tag: "live" (psutil/real), "seed" (synthetic seed_data.py), "simulated" (simulator)
    # Displayed as a colored badge in the dashboard so viewers know data provenance.
    data_source = Column(String, default="live")
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc))

    __table_args__ = (
        Index("ix_m_tenant_source_cat_time", "tenant_id", "source_id", "category", "event_time"),
    )
